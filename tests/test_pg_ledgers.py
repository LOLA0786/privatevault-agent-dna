"""Lineage, circuit-breaker and replay ledgers on PostgreSQL.

With PV_DATABASE_URL set these ledgers move into the same database as the
decision ledger, through PgCompatConnection, which keeps SQLite's "one
writer per ledger at a time" rule across every instance. Runs against a
real PostgreSQL when TEST_DATABASE_URL is set (CI starts one); skipped
otherwise.

Covered: the compat layer (translation, lock release on a failed
statement), breaker behaviour and log hashes identical to SQLite, a volume
cap that holds under 20 concurrent reservations from two instances (fails
without the ledger lock), a trip seen by every instance, lineage chains
that never fork and a single approval winner across instances, a signed
flow exported from the API on PostgreSQL that verifies offline, replay
inputs in a separate database, and the runtime wiring.
"""

