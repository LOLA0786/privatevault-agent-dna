def test_replay_inputs_in_a_separate_postgres_database(dsn):
    from agent_dna.policy_replay import ReplayInputStore

    store = ReplayInputStore(path=dsn, retain_fields=["amount"])
    try:
        store.capture("d1", "a1", "pay", {"amount": 5, "iban": "secret"})
        store.capture("d1", "a1", "pay", {"amount": 7})  # upsert, not a duplicate
        rows = list(store.iter_inputs())
        assert [(r["decision_id"], r["retained"]) for r in rows] == [
            ("d1", {"amount": 7})
        ]
        assert store.purge_before(time.time() + 1) == 1
        assert list(store.iter_inputs()) == []
    finally:
        store.close()


