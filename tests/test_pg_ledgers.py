class Clock:
    def __init__(self) -> None:
        self.t = 1_000_000.0

    def __call__(self) -> float:
        return self.t


# ---- compat layer ------------------------------------------------------------


def test_translation_of_the_portable_subset():
    ddl = to_pg(
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL, realm TEXT)"
    )
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "ts DOUBLE PRECISION" in ddl and "realm TEXT" in ddl
    assert to_pg("ALTER TABLE t ADD COLUMN x TEXT").endswith("IF NOT EXISTS x TEXT")
    assert to_pg("SELECT a FROM t WHERE b = ? AND c LIKE '5%'") == (
        "SELECT a FROM t WHERE b = %s AND c LIKE '5%%'"
    )
    assert to_pg("UPDATE t SET ts = ?") == "UPDATE t SET ts = %s"  # DML untouched


def test_failed_statement_releases_the_ledger_lock(pools):
    one = PgCompatConnection(pools[0], "t")
    two = PgCompatConnection(pools[1], "t")
    one.execute("CREATE TABLE IF NOT EXISTS u (k TEXT PRIMARY KEY)")
    one.commit()
    assert one.execute("PRAGMA journal_mode=WAL").fetchall() == []
    one.execute("INSERT INTO u (k) VALUES (?)", ("a",))
    one.commit()
    with pytest.raises(sqlite3.IntegrityError):
        one.execute("INSERT INTO u (k) VALUES (?)", ("a",))
    assert not one.in_transaction  # the caller forgot to roll back ...
    done = threading.Event()

    def other_instance_writes():
        two.execute("INSERT INTO u (k) VALUES (?)", ("b",))
        two.commit()
        done.set()

    threading.Thread(target=other_instance_writes).start()
    assert done.wait(5), "ledger lock leaked after a failed statement"
    assert one.execute("SELECT k FROM u ORDER BY k").fetchall() == [("a",), ("b",)]


# ---- circuit breaker ---------------------------------------------------------


def _scenario(breaker: CircuitBreaker, clock: Clock) -> list[object]:
    out: list[object] = []
    for _ in range(3):
        clock.t += 1
        out.append(breaker.reserve("a1", Decimal("30")))
        out.append(breaker.finalize(out[-1][1], "allow"))  # type: ignore[index]
    clock.t += 1
    out.append(breaker.reserve("a1", Decimal("30")))  # 120 > 100: volume trip
    out.append(breaker.pre_gate("a1"))
    out.append(breaker.reset("a1", "ops", lambda *_: True)["record_hash"])
    for _ in range(3):
        clock.t += 1
        out.append(breaker.observe("a2", "block", Decimal("1")))  # refusal thrash
    clock.t += 1
    out.append(breaker.reserve("g1", Decimal("60")))
    out.append(breaker.reserve("g2", Decimal("60")))  # group cap 100 crossed
    out.append((breaker.is_tripped("g1"), breaker.is_tripped("g2")))
    out.append(breaker.verify_log())
    return out


def _config() -> BreakerConfig:
    return BreakerConfig(
        window_seconds=3600,
        max_cumulative_amount=100,
        max_consecutive_refusals=3,
        groups={"swarm": ["g1", "g2"]},
        group_volume_caps={"swarm": 100},
    )


def test_breaker_on_postgres_matches_sqlite(pools, tmp_path):
    lite_clock, pg_clock = Clock(), Clock()
    lite = CircuitBreaker(tmp_path / "b.db", _config(), clock=lite_clock)
    pg = CircuitBreaker(
        PgCompatConnection(pools[0], "breaker"), _config(), clock=pg_clock
    )
    assert _scenario(pg, pg_clock) == _scenario(lite, lite_clock)
    assert pg.verify_log()


def test_volume_cap_holds_across_instances_under_concurrency(pools):
    config = BreakerConfig(window_seconds=3600, max_cumulative_amount=100)
    breakers = [CircuitBreaker(PgCompatConnection(p, "breaker"), config) for p in pools]
    barrier = threading.Barrier(20)
    reserved: list[int] = []
    lock = threading.Lock()

    def go(i):
        barrier.wait()
        reason, rid = breakers[i % 2].reserve("a1", "10")
        if rid is not None:
            with lock:
                reserved.append(rid)

    threads = [threading.Thread(target=go, args=(i,)) for i in range(20)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert len(reserved) == 10  # exactly the cap, never more
    rows = (
        breakers[0]
        ._conn.execute("SELECT COUNT(*) FROM breaker_events WHERE agent_id = 'a1'")
        .fetchone()
    )
    assert rows == (10,)


def test_a_trip_on_one_instance_blocks_on_every_instance(pools):
    config = BreakerConfig(max_consecutive_refusals=2)
    a, b = (CircuitBreaker(PgCompatConnection(p, "breaker"), config) for p in pools)
    a.observe("rogue", "block")
    assert a.observe("rogue", "block") is not None
    assert b.pre_gate("rogue") is not None  # instance B never saw the verdicts
    b.reset("rogue", "ops", lambda *_: True)
    assert a.pre_gate("rogue") is None
    assert a.verify_log() and b.verify_log()


# ---- lineage -----------------------------------------------------------------


def _ctx(agent: str, flow: str | None, intent: str = "other") -> LineageContext:
    return LineageContext(agent_norm=agent, capability="x", intent=intent, flow_id=flow)


def test_lineage_chain_never_forks_across_instances(pools):
    ledgers = [LineageLedger(PgCompatConnection(p, "lineage")) for p in pools]
    flow = ledgers[0].record(
        _ctx("a", None),
        record_hash="sha256:" + "0" * 64,
        decision_id="d0",
        decision="allow",
        claimed=False,
    )
    barrier = threading.Barrier(16)

    def go(i):
        barrier.wait()
        ledgers[i % 2].record(
            _ctx("a", flow),
            record_hash=f"{i + 1:064x}",
            decision_id=f"d{i + 1}",
            decision="allow",
            claimed=False,
        )

    threads = [threading.Thread(target=go, args=(i,)) for i in range(16)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    events = ledgers[1].export_flow(flow)
    assert [e["event"]["seq"] for e in events] == list(range(1, 18))
    prev = "0" * 64
    for e in events:
        assert e["event"]["prev_event_hash"] == prev
        prev = e["event_hash"]


def test_only_one_approval_wins_across_instances(pools):
    ledgers = [LineageLedger(PgCompatConnection(p, "lineage")) for p in pools]
    target = "ab" * 32
    wins: list[bool] = []
    barrier = threading.Barrier(10)

    def go(i):
        ctx = _ctx(f"checker-{i}", "flow:x", "approve")
        ctx.approves_record_hash = target
        barrier.wait()
        wins.append(ledgers[i % 2].claim_approval(ctx))

    threads = [threading.Thread(target=go, args=(i,)) for i in range(10)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert wins.count(True) == 1
    assert ledgers[1].approval_claimed(target)


