"""Per-agent baselines and cross-agent windows shared through PostgreSQL.

Until now two pieces of enforcement state lived in each API process:

* an agent's **behavioural baseline** (the last capability it was allowed
  to run), which drift scoring compares the next action against; and
* the **cross-agent (CABI) windows**: recent interaction events per
  declared execution, which the dual-control invariants evaluate.

Behind a load balancer each instance would have seen only its own share of
an agent's traffic. With ``PV_DATABASE_URL`` set, both live here instead,
with the in-memory semantics unchanged: the baseline advances only on
ALLOW (the monitor decides that), and a window keeps its newest
``max_window_events`` events while the ``max_executions`` most recently
used executions are kept (LRU, ordered by a database sequence so every
instance agrees on recency). Appends to one execution are serialised by a
transaction advisory lock, as the in-process lock did.
"""

from __future__ import annotations

import json
import time
from dataclasses import asdict
from typing import Any

from .multi_agent import InteractionEvent

_SCHEMA = """
CREATE TABLE IF NOT EXISTS agent_baselines (
    agent_id            TEXT PRIMARY KEY,
    previous_capability TEXT,
    updated_at          DOUBLE PRECISION NOT NULL
);
CREATE SEQUENCE IF NOT EXISTS cabi_recency;
CREATE TABLE IF NOT EXISTS cabi_executions (
    execution_id TEXT PRIMARY KEY,
    last_used    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS cabi_executions_last_used
    ON cabi_executions (last_used);
CREATE TABLE IF NOT EXISTS cabi_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id TEXT NOT NULL
        REFERENCES cabi_executions (execution_id) ON DELETE CASCADE,
    event_json   TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS cabi_events_window ON cabi_events (execution_id, id);
"""


def _ensure_schema(pool: Any) -> None:
    with pool.connection() as conn:
        conn.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
            ("pv:schema:shared",),
        )
        conn.execute(_SCHEMA)


class _AgentBaseline:
    """One agent's baseline; satisfies runtime.AgentState."""

    def __init__(self, pool: Any, agent_id: str) -> None:
        self._pool = pool
        self.agent_id = agent_id

    def get(self) -> str | None:
        with self._pool.connection() as conn:
            row = conn.execute(
                "SELECT previous_capability FROM agent_baselines WHERE agent_id = %s",
                (self.agent_id,),
            ).fetchone()
        return None if row is None else row[0]

    def set(self, capability: str | None) -> None:
        with self._pool.connection() as conn:
            conn.execute(
                "INSERT INTO agent_baselines (agent_id, previous_capability, updated_at) "
                "VALUES (%s, %s, %s) ON CONFLICT (agent_id) DO UPDATE SET "
                "previous_capability = excluded.previous_capability, "
                "updated_at = excluded.updated_at",
                (self.agent_id, capability, time.time()),
            )


class PostgresAgentBaselines:
    def __init__(self, pool: Any) -> None:
        self._pool = pool
        _ensure_schema(pool)

    def for_agent(self, agent_id: str) -> _AgentBaseline:
        return _AgentBaseline(self._pool, agent_id)


def _dump(event: InteractionEvent) -> str:
    return json.dumps(asdict(event), sort_keys=True, separators=(",", ":"))


def _load(raw: str) -> InteractionEvent:
    return InteractionEvent(**json.loads(raw))


class PostgresWindows:
    """CABI execution windows shared by every instance (WindowStore)."""

    def __init__(self, pool: Any) -> None:
        self._pool = pool
        _ensure_schema(pool)

    def window(self, execution_id: str) -> list[InteractionEvent]:
        with self._pool.connection() as conn:
            rows = conn.execute(
                "SELECT event_json FROM cabi_events WHERE execution_id = %s ORDER BY id",
                (execution_id,),
            ).fetchall()
        return [_load(r[0]) for r in rows]

    def append(
        self,
        event: InteractionEvent,
        *,
        max_window_events: int,
        max_executions: int,
    ) -> list[InteractionEvent]:
        eid = event.execution_id
        with self._pool.connection() as conn:
            conn.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                (f"pv:cabi:{eid}",),
            )
            conn.execute(
                "INSERT INTO cabi_executions (execution_id, last_used) "
                "VALUES (%s, nextval('cabi_recency')) ON CONFLICT (execution_id) "
                "DO UPDATE SET last_used = excluded.last_used",
                (eid,),
            )
            conn.execute(
                "INSERT INTO cabi_events (execution_id, event_json) VALUES (%s, %s)",
                (eid, _dump(event)),
            )
            conn.execute(
                "DELETE FROM cabi_events WHERE execution_id = %s AND id NOT IN ("
                "SELECT id FROM cabi_events WHERE execution_id = %s "
                "ORDER BY id DESC LIMIT %s)",
                (eid, eid, max_window_events),
            )
            rows = conn.execute(
                "SELECT event_json FROM cabi_events WHERE execution_id = %s ORDER BY id",
                (eid,),
            ).fetchall()
            # LRU: keep the max_executions most recently used executions.
            conn.execute(
                "DELETE FROM cabi_executions WHERE last_used < ("
                "SELECT last_used FROM cabi_executions ORDER BY last_used DESC "
                "OFFSET %s LIMIT 1)",
                (max_executions - 1,),
            )
        return [_load(r[0]) for r in rows]
