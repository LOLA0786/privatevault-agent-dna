"""Run a SQLite-written ledger on PostgreSQL with SQLite's write semantics.

The lineage, circuit-breaker and replay-input ledgers are written against
``sqlite3`` with a small portable SQL subset. Rather than keep a second copy
of their logic, :class:`PgCompatConnection` gives them a connection-shaped
object backed by a psycopg pool, and keeps the guarantee their code relies on:

* **One writer per ledger at a time.** SQLite serialises every writer of a
  file: the first write of a transaction (or ``BEGIN IMMEDIATE``) takes the
  write lock until commit or rollback. Here the same moment takes a
  transaction advisory lock named after the ledger, held on that connection
  until commit or rollback, across every instance sharing the database.
  Reads under the lock see every earlier writer's commits (READ COMMITTED
  takes a fresh snapshot per statement).
* **Reads outside a transaction** run on a borrowed connection and return
  at once, as SQLite's autocommit reads do.
* A failed statement rolls the whole transaction back (PostgreSQL aborts
  it anyway), releasing the lock; ledgers must not catch an error and keep
  writing in the same transaction.
* Transaction state is per thread, so one object is safe to share between
  threads (a SQLite connection is not).

Translation is deliberately small: ``?`` placeholders, ``REAL`` (which is
4-byte in PostgreSQL) to ``DOUBLE PRECISION`` and ``AUTOINCREMENT`` keys to
identity columns in DDL, ``ADD COLUMN IF NOT EXISTS``, ``PRAGMA`` ignored,
and unique violations raised as ``sqlite3.IntegrityError``. Ledger SQL must
otherwise be portable (upserts as ``ON CONFLICT``, ids via ``RETURNING``).
"""

from __future__ import annotations

import re
import sqlite3
import threading
from collections.abc import Iterator, Sequence
from typing import Any

try:
    from psycopg import errors as _pg_errors
except ImportError:  # pragma: no cover - the postgres extra is not installed
    _pg_errors = None  # type: ignore[assignment]

_WRITES = frozenset({"INSERT", "UPDATE", "DELETE", "CREATE", "ALTER", "DROP"})
_DDL = frozenset({"CREATE", "ALTER"})


def to_pg(sql: str) -> str:
    """Translate one statement of the portable subset to PostgreSQL."""
    out = sql.strip().replace("%", "%%").replace("?", "%s")
    if out.split(None, 1)[0].upper() in _DDL:
        out = re.sub(
            r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            out,
            flags=re.IGNORECASE,
        )
        out = re.sub(r"\bREAL\b", "DOUBLE PRECISION", out, flags=re.IGNORECASE)
        out = re.sub(
            r"\bADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)",
            "ADD COLUMN IF NOT EXISTS ",
            out,
            flags=re.IGNORECASE,
        )
    return out


class _Result:
    """The parts of ``sqlite3.Cursor`` the ledgers use."""

    def __init__(self, rows: list[tuple[Any, ...]], rowcount: int) -> None:
        self._rows = rows
        self._i = 0
        self.rowcount = rowcount

    def fetchone(self) -> tuple[Any, ...] | None:
        if self._i >= len(self._rows):
            return None
        row = self._rows[self._i]
        self._i += 1
        return row

    def fetchall(self) -> list[tuple[Any, ...]]:
        rows, self._i = self._rows[self._i :], len(self._rows)
        return rows

    def __iter__(self) -> Iterator[tuple[Any, ...]]:
        return iter(self.fetchall())


class PgCompatConnection:
    """``sqlite3.Connection``-shaped access to one ledger in PostgreSQL."""

    def __init__(self, pool: Any, ledger: str, *, owns_pool: bool = False) -> None:
        if not ledger:
            raise ValueError("ledger name is required (it names the write lock)")
        self.pool = pool
        self.ledger = ledger
        self._owns_pool = owns_pool
        self._tx = threading.local()

    # ---- transactions --------------------------------------------------

    def _held(self) -> Any | None:
        return getattr(self._tx, "conn", None)

    def _begin(self) -> Any:
        conn = self._held()
        if conn is not None:
            return conn
        cm = self.pool.connection()
        conn = cm.__enter__()
        try:
            conn.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                (f"pv:ledger:{self.ledger}",),
            )
        except BaseException as exc:
            cm.__exit__(type(exc), exc, exc.__traceback__)
            raise
        self._tx.cm, self._tx.conn = cm, conn
        return conn

    def _end(self, commit: bool) -> None:
        conn = self._held()
        if conn is None:
            return
        cm = self._tx.cm
        self._tx.cm = self._tx.conn = None
        try:
            if commit:
                conn.commit()
            else:
                conn.rollback()
        finally:
            cm.__exit__(None, None, None)

    def commit(self) -> None:
        self._end(commit=True)

    def rollback(self) -> None:
        self._end(commit=False)

    @property
    def in_transaction(self) -> bool:
        return self._held() is not None

    # ---- statements ----------------------------------------------------

    def execute(self, sql: str, params: Sequence[Any] = ()) -> _Result:
        head = sql.strip().split(None, 1)[0].upper()
        if head == "PRAGMA":
            return _Result([], -1)
        if head == "BEGIN":
            self._begin()
            return _Result([], -1)
        conn = self._begin() if head in _WRITES else self._held()
        if conn is None:
            with self.pool.connection() as borrowed:
                return self._run(borrowed, sql, params)
        try:
            return self._run(conn, sql, params)
        except BaseException:
            # PostgreSQL aborts the whole transaction on a failed statement
            # (SQLite fails only the statement). End it now so the ledger
            # lock is released even if the caller does not roll back.
            self._end(commit=False)
            raise

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            if statement.strip() and not statement.strip().startswith("--"):
                self.execute(statement)

    @staticmethod
    def _run(conn: Any, sql: str, params: Sequence[Any]) -> _Result:
        try:
            cur = conn.execute(to_pg(sql), tuple(params) or None)
        except Exception as exc:
            if _pg_errors is not None and isinstance(exc, _pg_errors.UniqueViolation):
                raise sqlite3.IntegrityError(str(exc)) from exc
            raise
        rows = [tuple(r) for r in cur.fetchall()] if cur.description else []
        return _Result(rows, cur.rowcount)

    def close(self) -> None:
        self.rollback()
        if self._owns_pool:
            self.pool.close()

    def __repr__(self) -> str:
        return f"PgCompatConnection(ledger={self.ledger!r})"


def is_database_url(target: object) -> bool:
    return isinstance(target, str) and target.startswith(
        ("postgresql://", "postgres://")
    )


def connect_url(url: str, ledger: str) -> PgCompatConnection:
    """A ledger connection with its own small pool (e.g. a separate database)."""
    from psycopg_pool import ConnectionPool

    pool = ConnectionPool(
        url, min_size=1, max_size=4, kwargs={"autocommit": False}, open=True
    )
    return PgCompatConnection(pool, ledger, owns_pool=True)
