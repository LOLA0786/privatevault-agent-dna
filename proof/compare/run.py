"""Run the comparison matrix, print the table, write RESULTS.md and JSON.

    uv run python -m proof.compare.run

Exit status 0 only if the expected shape holds: every control admits the
honest request, the three conventional controls admit both alterations,
and the receiver gate refuses both with RECEIVER_WIRE_MISMATCH.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path

from proof.compare import attack, controls

HERE = Path(__file__).resolve().parent
RESULTS_MD = HERE / "RESULTS.md"

SCENARIOS: list[tuple[str, Callable[[], attack.Request]]] = [
    ("honest: 18,000 INR to V-100, as approved", attack.honest_request),
    ("altered amount: 48,000 INR", attack.altered_amount),
    ("altered payee: V-999", attack.altered_payee),
]

GATEWAY_SENTENCE = (
    "A gateway can only catch this by verifying a signed approval bound to "
    "the exact request bytes, which is what PrivateVault's receiver gate does."
)

Matrix = dict[str, dict[str, controls.Verdict]]


def run_matrix(*, gateway_cap: int = 50000) -> Matrix:
    """Fresh controls per scenario: each sees the approval, then one request."""
    matrix: Matrix = {}
    workdir = Path(tempfile.mkdtemp(prefix="pv-compare-"))
    for index, (scenario, make_request) in enumerate(SCENARIOS):
        request = make_request()
        row: dict[str, controls.Verdict] = {}
        for control in controls.build_controls(
            gateway_cap=gateway_cap, workdir=workdir / f"s{index}"
        ):
            control.approve(attack.INTENT)
            row[control.name] = control.admit(request)
        matrix[scenario] = row
    return matrix


def low_cap_counter_case(cap: int = 10000) -> dict[str, controls.Verdict]:
    gateway = controls.ApiGateway(valid_keys={attack.API_KEY}, cap=cap)
    gateway.approve(attack.INTENT)
    return {
        "honest": gateway.admit(attack.honest_request()),
        "altered": gateway.admit(attack.altered_amount()),
    }


def expected_shape(matrix: Matrix) -> bool:
    gate = controls.ReceiverGateControl.name
    honest, altered = SCENARIOS[0][0], [s for s, _ in SCENARIOS[1:]]
    if not all(v.admitted for v in matrix[honest].values()):
        return False
    for scenario in altered:
        for name, verdict in matrix[scenario].items():
            if name == gate:
                if verdict.admitted or verdict.reason != "RECEIVER_WIRE_MISMATCH":
                    return False
            elif not verdict.admitted:
                return False
    return True


def control_names(matrix: Matrix) -> list[str]:
    return list(next(iter(matrix.values())).keys())


def render_table(matrix: Matrix) -> str:
    names = control_names(matrix)
    scenarios = list(matrix)

    def cell(scenario: str, name: str) -> str:
        verdict = matrix[scenario][name]
        return "ADMITTED" if verdict.admitted else f"REFUSED {verdict.reason}"

    width = max(len(n) for n in names) + 2
    cols = [max(len(s), *(len(cell(s, n)) for n in names)) + 2 for s in scenarios]
    lines = [
        "Setup".ljust(width)
        + "".join(s.ljust(c) for s, c in zip(scenarios, cols, strict=True))
    ]
    lines.append("-" * (width + sum(cols)))
    for name in names:
        lines.append(
            name.ljust(width)
            + "".join(
                cell(s, name).ljust(c) for s, c in zip(scenarios, cols, strict=True)
            )
        )
    return "\n".join(lines)


def render_results(matrix: Matrix) -> str:
    """Deterministic Markdown: no timestamps, no run ids, so a fresh run must
    reproduce the committed file byte for byte."""
    names = control_names(matrix)
    scenarios = list(matrix)
    counter = low_cap_counter_case()
    lines = [
        "# One attack, four controls",
        "",
        "Generated by `uv run python -m proof.compare.run`. Do not edit by hand;",
        "`tests/proof/test_compare.py::test_committed_results_match_a_fresh_run`",
        "fails if this file differs from a fresh run.",
        "",
        "## The attack",
        "",
        "An agent holding valid credentials obtains an approved intent: pay",
        f"invoice {attack.INTENT['invoice_id']}, {attack.INTENT['amount']:,} INR to vendor "
        f"{attack.INTENT['payee_id']}. Its own process then changes the request before",
        "sending: the amount becomes 48,000, or the payee becomes V-999. The",
        "credentials, headers, and request shape are unchanged. The attacker mints a",
        "fresh idempotency key, because the caller controls that header.",
        "",
        "## Results",
        "",
        "| Setup | " + " | ".join(scenarios) + " |",
        "|---|" + "---|" * len(scenarios),
    ]
    for name in names:
        cells = [matrix[s][name].label for s in scenarios]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## How each control was modelled",
        "",
        "- a) LLM guardrail stub: a content filter over the tool-call text, run at",
        "  approval and again on the outgoing request. It catches injection and",
        "  exfiltration phrases and card-number shapes. An altered payment is",
        "  benign text, so it passes.",
        "- b) API gateway: API-key authentication plus an OPA-style rule",
        "  `amount < cap`, cap 50,000 as in the persona policy. The key is valid",
        "  and 48,000 < 50,000, so it passes. A changed payee is not a policy",
        "  input at all.",
        "- c) Idempotency key: strict deduplication (same key with a different",
        "  body is rejected). The attacker mints a fresh key, so it passes.",
        "- d) PrivateVault receiver gate: the real `ReceiverGate` with a permit",
        "  minted for the approved bytes. The bytes that arrive are not the",
        "  bytes that were approved, so it refuses with `RECEIVER_WIRE_MISMATCH`.",
        "",
        "## Footnotes",
        "",
        f"1. A gateway cap of 10,000 refuses the altered 48,000 request ({counter['altered'].label})",
        f"   and the approved 18,000 request alike ({counter['honest'].label}). Thresholds",
        "   classify amounts; they do not know what was approved.",
        "2. Strict idempotency catches reuse of the approved key with a different",
        "   body, and nothing else. The caller chooses the key.",
        f"3. {GATEWAY_SENTENCE}",
        "",
    ]
    return "\n".join(lines)


def to_json(matrix: Matrix) -> dict:
    return {
        scenario: {
            name: {"admitted": v.admitted, "reason": v.reason}
            for name, v in row.items()
        }
        for scenario, row in matrix.items()
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", default=str(RESULTS_MD))
    parser.add_argument("--json", default=None)
    args = parser.parse_args(argv)
    matrix = run_matrix()
    print(render_table(matrix))
    print()
    counter = low_cap_counter_case()
    print(
        f"footnote: gateway cap 10,000 -> honest {counter['honest'].label}; altered {counter['altered'].label}"
    )
    print(f"footnote: {GATEWAY_SENTENCE}")
    Path(args.results).write_text(render_results(matrix), encoding="utf-8")
    if args.json:
        Path(args.json).write_text(
            json.dumps(to_json(matrix), indent=2), encoding="utf-8"
        )
    ok = expected_shape(matrix)
    print()
    print("EXPECTED SHAPE HOLDS" if ok else "UNEXPECTED SHAPE")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
