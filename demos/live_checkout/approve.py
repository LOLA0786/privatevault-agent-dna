"""The human approver's terminal.

    uv run python demos/live_checkout/approve.py            # watch and decide
    uv run python demos/live_checkout/approve.py --auto approve --once   # tests

Shows each pending approval: the exact action PrivateVault was asked about
(amount, payee, order id), the digest and length of the order bytes the
permit would be bound to, and why the policy escalated. ``approve`` signs
an ``approval_v01`` artifact for exactly that action with the approver's
own key (generated by ``bootstrap.py``, kept in the run directory, never
sent anywhere); ``deny`` records a denial. A denial never changes a
verdict; an approval is bound to this action digest and this request id.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # run as a script

from agent_dna.authority_v01 import sha256_digest  # noqa: E402
from agents.core.approval import ApproverKit  # noqa: E402
from demos.live_checkout import config as cfg  # noqa: E402
from demos.live_checkout.approvals import ApprovalInbox, PendingApproval  # noqa: E402
from demos.live_checkout.bootstrap import approver_from_secret  # noqa: E402
from demos.live_checkout.events import (
    BOLD,
    DIM,
    GREEN,
    RED,
    RESET,
    YELLOW,
    colour_enabled,
    log,
)  # noqa: E402


def inr(amount: object) -> str:
    try:
        n = int(str(amount))
    except (TypeError, ValueError):
        return str(amount)
    s = str(abs(n))
    if len(s) <= 3:
        return "₹" + s
    head, tail = s[:-3], s[-3:]
    parts: list[str] = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return ("-" if n < 0 else "") + "₹" + ",".join(parts) + "," + tail


def show(item: PendingApproval) -> None:
    c = colour_enabled()
    b, d, y, r = (BOLD, DIM, YELLOW, RESET) if c else ("", "", "", "")
    p = item.parameters
    print()
    print(
        f"{y}{b}APPROVAL REQUESTED{r}  {d}{item.submitted_at}  request {item.request_id}{r}"
    )
    print(f"  {d}reason{r}      {item.reason}")
    print(
        f"  {d}action{r}      {item.action.get('action')}  on  {item.action.get('resource')}"
    )
    print(f"  {d}amount{r}      {b}{inr(p.get('amount'))} {p.get('currency', '')}{r}")
    payee = p.get("payee", p.get("merchant_id"))
    original = p.get("original_payee")
    same = (
        ""
        if original is None
        else (
            f"  {d}(original instrument){r}"
            if payee == original
            else f"  {b}(NOT the original: {original}){r}"
        )
    )
    print(f"  {d}payee{r}       {b}{payee}{r}{same}")
    print(
        f"  {d}order{r}       {p.get('order_id')}  customer {p.get('customer_id', '-')}"
        f"  refund {p.get('refund_id', '-')}"
    )
    if original is not None:
        print(
            f"  {d}facts{r}       original {inr(p.get('original_amount'))}"
            f"  prior refunds on order {p.get('prior_refunds_for_order')}"
            f"  customer refunds today {p.get('customer_refunds_today')}"
        )
    print(f"  {d}order bytes{r} {item.wire_digest} ({item.wire_length} B)")
    print(f"  {d}action hash{r} {sha256_digest(item.action)}")
    for label, key in (
        ("request", "request"),
        ("customer", "customer_text"),
        ("claude", "claude_reason"),
        ("agent task", "task"),
    ):
        value = item.context.get(key)
        if value:
            print(f"  {d}{label:<11}{r} {value}")


def decide(
    inbox: ApprovalInbox, kit: ApproverKit, item: PendingApproval, approved: bool
) -> None:
    approval = None
    if approved:
        approval = kit.approve(item.action, request_id=item.request_id)
    inbox.decide(item, approved=approved, approval=approval, approver=kit.principal)
    if approved:
        digest = sha256_digest(approval["artifact"]) if approval else None
        log(
            "approver", "APPROVED", "APPROVED", request=item.request_id, approval=digest
        )
    else:
        log("approver", "DENIED", "DENIED", request=item.request_id)


def ask(item: PendingApproval) -> bool | None:
    c = colour_enabled()
    g, r, x = (GREEN, RED, RESET) if c else ("", "", "")
    while True:
        try:
            answer = input(f"  {g}approve{x} / {r}deny{x} / skip? ").strip().lower()
        except EOFError:
            return None
        if answer in {"approve", "a", "y", "yes"}:
            return True
        if answer in {"deny", "d", "n", "no"}:
            return False
        if answer in {"skip", "s", ""}:
            return None


def run(
    inbox: ApprovalInbox,
    kit: ApproverKit,
    *,
    auto: str | None,
    once: bool,
    poll_s: float,
) -> int:
    seen: set[str] = set()
    handled = 0
    log(
        "approver",
        "READY",
        "",
        principal=kit.principal,
        key=kit.key_id,
        inbox=str(inbox.root),
    )
    while True:
        for item in inbox.pending():
            if item.request_id in seen:
                continue
            show(item)
            if auto is not None:
                verdict: bool | None = auto == "approve"
                print(f"  auto: {auto}")
            else:
                verdict = ask(item)
            if verdict is None:
                seen.add(item.request_id)
                continue
            decide(inbox, kit, item, verdict)
            seen.add(item.request_id)
            handled += 1
            if once:
                return 0
        time.sleep(poll_s)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-dir", default=None)
    parser.add_argument(
        "--auto",
        choices=["approve", "deny"],
        default=None,
        help="decide without asking (tests)",
    )
    parser.add_argument("--once", action="store_true", help="exit after one decision")
    parser.add_argument("--poll", type=float, default=0.5)
    args = parser.parse_args(argv)
    run_dir = Path(args.run_dir) if args.run_dir else cfg.run_dir()
    key_file = run_dir / "approver" / "secret.json"
    if not key_file.exists():
        print(
            "no approver key in the run directory; run bootstrap.py first",
            file=sys.stderr,
        )
        return 2
    kit = approver_from_secret(key_file)
    inbox = ApprovalInbox(run_dir / "approvals")
    try:
        return run(inbox, kit, auto=args.auto, once=args.once, poll_s=args.poll)
    except KeyboardInterrupt:
        print()
        return 0


if __name__ == "__main__":
    sys.exit(main())
