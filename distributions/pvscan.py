def _iter_json_lines(path: Path) -> Iterator[tuple[int, str]]:
    with path.open("r", encoding="utf-8", errors="replace") as fh:
        yield from enumerate(fh, start=1)


def _ingest_csv(path: Path, result: IngestResult) -> None:
    with path.open("r", encoding="utf-8", errors="replace", newline="") as fh:
        text = fh.read()
    if not text.strip():
        return
    try:
        dialect = _csv.Sniffer().sniff(text[:4096], delimiters=",;\t|")
    except _csv.Error:
        dialect = _csv.excel
    reader = _csv.DictReader(io.StringIO(text), dialect=dialect)
    for line_no, row in enumerate(reader, start=2):  # 1 is the header
        result.lines_read += 1
        clean = {k.strip(): v for k, v in row.items() if k}
        built = _build_action(clean, line_no, "csv")
        if isinstance(built, SkippedRow):
            result.skipped.append(built)
        else:
            result.actions.append(built)


def _ingest_sqlite(
    path: Path,
    agent_id: str | None,
    result: IngestResult,
) -> None:
    """Read PrivateVault's append-only records table without writing the DB."""
    uri = f"file:{path.resolve()}?mode=ro"
    try:
        connection = sqlite3.connect(uri, uri=True)
    except sqlite3.Error as exc:
        raise ValueError(f"cannot open SQLite history read-only: {exc}") from exc

    try:
        tables = {
            row[0]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table'"
            )
        }
        if "records" not in tables:
            raise ValueError("SQLite history has no records table")

        columns = {row[1] for row in connection.execute("PRAGMA table_info(records)")}
        if not {"seq", "body"}.issubset(columns):
            raise ValueError("SQLite records table must contain seq and body")

        for line_no, (body,) in enumerate(
            connection.execute("SELECT body FROM records ORDER BY seq"),
            start=1,
        ):
            result.lines_read += 1
            try:
                obj = json.loads(body)
            except (TypeError, ValueError) as exc:
                result.skipped.append(
                    SkippedRow(
                        line_no,
                        f"invalid record body JSON: {str(exc)[:60]}",
                        str(body)[:_MAX_RAW_ECHO],
                    )
                )
                continue
            if not isinstance(obj, dict):
                result.skipped.append(
                    SkippedRow(
                        line_no,
                        "record body is not a JSON object",
                        str(body)[:_MAX_RAW_ECHO],
                    )
                )
                continue
            _ingest_row(obj, line_no, "sqlite", agent_id, result)
    except sqlite3.Error as exc:
        raise ValueError(f"cannot read SQLite history: {exc}") from exc
    finally:
        connection.close()


def _ingest_row(
    flat: dict[str, Any],
    line_no: int,
    resolved: str,
    agent_id: str | None,
    result: IngestResult,
) -> None:
    built = _build_action(flat, line_no, resolved)
    if (
        isinstance(built, SkippedRow)
        and built.reason == "no agent identifier"
        and agent_id
    ):
        retry = dict(flat)
        retry["agent_id"] = agent_id
        built = _build_action(retry, line_no, resolved)
        if isinstance(built, AgentAction):
            built.context["agent_id_supplied"] = True
    if isinstance(built, SkippedRow):
        result.skipped.append(built)
    else:
        result.actions.append(built)


def _ingest_jsonl(
    path: Path,
    resolved: str,
    agent_id: str | None,
    result: IngestResult,
) -> None:
    extract = _EXTRACTORS[resolved]
    for line_no, line in _iter_json_lines(path):
        stripped = line.strip()
        if not stripped:
            continue
        result.lines_read += 1
        try:
            obj = json.loads(stripped)
        except ValueError as exc:
            result.skipped.append(
                SkippedRow(
                    line_no,
                    f"invalid JSON: {exc.args[0][:60]}",
                    stripped[:_MAX_RAW_ECHO],
                )
            )
            continue
        if not isinstance(obj, dict):
            result.skipped.append(
                SkippedRow(
                    line_no, "line is not a JSON object", stripped[:_MAX_RAW_ECHO]
                )
            )
            continue
        # Protocol chatter in a well-formed log is expected and is not a
        # failure to understand it, so an empty extraction is not a skip.
        for flat in extract(obj):
            _ingest_row(flat, line_no, resolved, agent_id, result)


def ingest(
    path: str | Path,
    fmt: str = "auto",
    *,
    agent_id: str | None = None,
) -> IngestResult:
    """Read a log file into actions.

    agent_id is a LAST-RESORT override for logs that genuinely carry no
    identity (a single-agent stdio session, say). It is applied only to
    rows that would otherwise be skipped for that reason, and the
    substitution is recorded in the action's context so the report can
    say the identity was supplied rather than observed.
    """
    if fmt not in FORMATS:
        raise ValueError(f"unknown format {fmt!r}; expected one of {FORMATS}")

    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"no such log file: {path}")

    resolved = detect_format(path) if fmt == "auto" else fmt
    result = IngestResult(source_format=resolved, source_path=str(path))

    if resolved == "csv":
        _ingest_csv(path, result)
    elif resolved == "sqlite":
        _ingest_sqlite(path, agent_id, result)
    else:
        _ingest_jsonl(path, resolved, agent_id, result)
    return result


