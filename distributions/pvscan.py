@dataclass(frozen=True)
class Rule:
    """One classification rule. `pattern` matches a capability name."""

    pattern: str
    effect: str
    note: str

    def matches(self, capability: str) -> bool:
        return re.fullmatch(self.pattern, capability, re.IGNORECASE) is not None


