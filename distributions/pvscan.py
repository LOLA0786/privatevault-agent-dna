def _first(obj: dict[str, Any], keys: tuple[str, ...]) -> Any:
    for k in keys:
        if k in obj and obj[k] not in (None, ""):
            return obj[k]
    return None


def parse_timestamp(value: Any) -> float | None:
    """Epoch seconds, epoch millis, or ISO 8601. Returns None rather
    than a fallback -- an action with an invented time would silently
    corrupt every rate and window calculation downstream."""
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        ts = float(value)
        # Heuristic only for the magnitude, never for existence:
        # anything past year ~2286 in seconds is milliseconds.
        if ts > 1e11:
            ts /= 1000.0
        return ts if ts > 0 else None
    if isinstance(value, str):
        text = value.strip()
        if not text:
            return None
        try:
            return parse_timestamp(float(text))
        except ValueError:
            pass
        cleaned = text.replace("Z", "+00:00")
        try:
            dt = datetime.fromisoformat(cleaned)
        except ValueError:
            return None
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=UTC)
        return dt.timestamp()
    return None


def _coerce_arguments(value: Any) -> dict[str, Any]:
    """Tool arguments arrive as a dict or as a JSON string. A string
    that will not parse is kept under a reserved key rather than
    discarded -- it may be the only record of what was attempted."""
    if isinstance(value, dict):
        return value
    if isinstance(value, str):
        try:
            parsed = json.loads(value)
        except (ValueError, TypeError):
            return {"_raw": value}
        return parsed if isinstance(parsed, dict) else {"_value": parsed}
    if value is None:
        return {}
    return {"_value": value}


def _normalize_capability(value: Any) -> str | None:
    if not isinstance(value, str):
        return None
    cap = value.strip()
    return cap or None


_DENIED = {
    "denied",
    "deny",
    "refused",
    "refuse",
    "rejected",
    "reject",
    "declined",
    "decline",
    "blocked",
    "block",
    "forbidden",
    "denied_by_policy",
    "policy_denied",
    "not_permitted",
}
_ERRORED = {"error", "fail", "failed", "failure", "exception", "timeout"}
_ALLOWED = {"ok", "allowed", "allow", "success", "succeeded", "completed"}


def _normalize_outcome(value: Any) -> str:
    """Map a log outcome onto ok/error/blocked. An unrecognised value
    is reported as unknown, never assumed benign."""
    if value is None:
        return "ok"
    t = str(value).strip().lower()
    if t in _DENIED:
        return "blocked"
    if t in _ERRORED:
        return "error"
    if t in _ALLOWED:
        return "ok"
    return "unknown"


def _build_action(
    obj: dict[str, Any],
    line_no: int,
    source_format: str,
) -> AgentAction | SkippedRow:
    raw = json.dumps(obj, default=str)[:_MAX_RAW_ECHO]

    agent_id = _first(obj, _AGENT_KEYS)
    if not isinstance(agent_id, str) or not agent_id.strip():
        return SkippedRow(line_no, "no agent identifier", raw)

    capability = _normalize_capability(_first(obj, _CAPABILITY_KEYS))
    if capability is None:
        return SkippedRow(line_no, "no capability/tool name", raw)

    timestamp = parse_timestamp(_first(obj, _TIMESTAMP_KEYS))
    if timestamp is None:
        return SkippedRow(line_no, "no parseable timestamp", raw)

    request_id = _first(obj, _REQUEST_KEYS)
    raw_outcome = obj.get("outcome") or obj.get("status")
    outcome = _normalize_outcome(raw_outcome)

    context: dict[str, Any] = {
        "source_format": source_format,
        "source_line": line_no,
    }
    if raw_outcome is not None:
        # Preserve exactly what the source claimed.  `outcome` is a legacy
        # normalization and is not proof that dispatch or an effect occurred.
        context["reported_outcome"] = str(raw_outcome)

    return AgentAction(
        agent_id=agent_id.strip(),
        capability=capability,
        timestamp=timestamp,
        arguments=_coerce_arguments(_first(obj, _ARGUMENT_KEYS)),
        context=context,
        request_id=str(request_id) if request_id is not None else None,
        outcome=outcome,
    )


