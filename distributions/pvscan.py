def _extract_mcp(obj: dict[str, Any]) -> list[dict[str, Any]]:
    """MCP JSON-RPC frame. Only tools/call carries an action; every
    other method (initialize, tools/list, notifications) is protocol
    chatter and is not an agent action."""
    if obj.get("method") != "tools/call":
        return []
    params = obj.get("params") or {}
    flat = dict(obj)
    flat.pop("params", None)
    flat["tool"] = params.get("name")
    flat["arguments"] = params.get("arguments")
    meta = params.get("_meta") or {}
    for key in _AGENT_KEYS:
        if key in meta:
            flat[key] = meta[key]
    return [flat]


def _extract_openai(obj: dict[str, Any]) -> list[dict[str, Any]]:
    """One chat-completion record may carry several tool_calls; each is
    a separate agent action."""
    calls: list[dict[str, Any]] = []
    choices = obj.get("choices") or []
    messages = [c.get("message", {}) for c in choices if isinstance(c, dict)]
    if "message" in obj and isinstance(obj["message"], dict):
        messages.append(obj["message"])
    if "tool_calls" in obj:
        messages.append(obj)

    for msg in messages:
        for call in msg.get("tool_calls") or []:
            fn = call.get("function") or {}
            flat = {k: v for k, v in obj.items() if k != "choices"}
            flat["tool"] = fn.get("name")
            flat["arguments"] = fn.get("arguments")
            flat["call_id"] = call.get("id")
            calls.append(flat)
    return calls


def _extract_anthropic(obj: dict[str, Any]) -> list[dict[str, Any]]:
    """Anthropic messages carry tool_use blocks in content."""
    calls: list[dict[str, Any]] = []
    content = obj.get("content")
    if isinstance(content, list):
        for block in content:
            if not isinstance(block, dict) or block.get("type") != "tool_use":
                continue
            flat = {k: v for k, v in obj.items() if k != "content"}
            flat["tool"] = block.get("name")
            flat["arguments"] = block.get("input")
            flat["call_id"] = block.get("id")
            calls.append(flat)
    return calls


def _extract_claude_code(obj: dict[str, Any]) -> list[dict[str, Any]]:
    """Claude Code / Cursor session lines nest the content array inside
    `message`, unlike the raw Anthropic API shape. Session identity comes
    from sessionId; the per-line uuid is the correlation id."""
    message = obj.get("message")
    if not isinstance(message, dict):
        return []
    content = message.get("content")
    if not isinstance(content, list):
        return []

    calls: list[dict[str, Any]] = []
    for block in content:
        if not isinstance(block, dict) or block.get("type") != "tool_use":
            continue
        flat = {k: v for k, v in obj.items() if k != "message"}
        flat["tool"] = block.get("name")
        flat["arguments"] = block.get("input")
        flat["call_id"] = block.get("id") or obj.get("uuid")
        calls.append(flat)
    return calls


def _extract_adr(obj: dict[str, Any]) -> list[dict[str, Any]]:
    """Uber ADR-Bench record: {type, task_id, conversation[], result{}}.

    The corpus identifies tasks, not agents, so no agent id exists in
    the data. Callers must supply one via ingest(agent_id=...); the
    substitution is recorded rather than invented here.
    """
    if obj.get("type") == "manifest":
        return []
    convo = obj.get("conversation")
    if not isinstance(convo, list):
        return []
    task = obj.get("task_id")
    res = obj.get("result") or {}
    ok = res.get("success")
    out: list[dict[str, Any]] = []
    for msg in convo:
        if not isinstance(msg, dict):
            continue
        for call in msg.get("tool_calls") or []:
            if not isinstance(call, dict):
                continue
            name = call.get("name")
            if not name:
                continue
            out.append(
                {
                    "capability": name,
                    "timestamp": msg.get("timestamp"),
                    "arguments": call.get("input") or call.get("arguments") or {},
                    "request_id": call.get("id"),
                    "outcome": "ok" if ok else ("error" if ok is False else None),
                    "task_id": task,
                }
            )
    return out


def _extract_generic(obj: dict[str, Any]) -> list[dict[str, Any]]:
    return [obj]


_EXTRACTORS = {
    "mcp": _extract_mcp,
    "openai": _extract_openai,
    "adr": _extract_adr,
    "anthropic": _extract_anthropic,
    "claude_code": _extract_claude_code,
    "generic": _extract_generic,
}


